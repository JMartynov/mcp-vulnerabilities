import logging
import subprocess
import json
from pathlib import Path
from typing import Any
from datetime import datetime

from .scanner import RemediationPlan

logger = logging.getLogger(__name__)


class PRBuilder:
    """Handles Git branch creation and GitHub PR generation."""

    def __init__(self, repo_root: Path, dry_run: bool = False, assignee: str | None = None, auto_merge: bool = False):
        self.repo_root = repo_root
        self.dry_run = dry_run
        self.assignee = assignee
        self.auto_merge = auto_merge

    def _run_cmd(self, cmd: list[str], check: bool = True) -> subprocess.CompletedProcess:
        """Run a shell command in the repo directory."""
        if self.dry_run and cmd[0] in ["git", "gh"] and cmd[1] not in ["status", "diff", "branch", "rev-parse"]:
            logger.info(f"[DRY-RUN] Executing: {' '.join(cmd)}")
            return subprocess.CompletedProcess(args=cmd, returncode=0, stdout=b"", stderr=b"")
            
        logger.debug(f"Executing: {' '.join(cmd)}")
        return subprocess.run(cmd, cwd=self.repo_root, capture_output=True, check=check)

    def format_pr_body(self, plan: RemediationPlan) -> str:
        """Generates a rich Markdown PR body with advisory tables and JSON diffs."""
        body = []
        body.append("## 🛡️ Automated MCP Security Remediation")
        body.append("\nThis PR automatically remediates vulnerable Model Context Protocol (MCP) server versions identified in your client configuration files.")
        
        body.append("\n### 📦 Vulnerable Packages Remediated")
        body.append("| Package Name | Installed Version | Target Safe Version | Severities (CVSS) |")
        body.append("| ------------ | ----------------- | ------------------- | ----------------- |")
        
        for change in plan.changes:
            # Find severities for this server
            pkg_findings = [f for f in plan.report.findings if f.server_name == change["server_name"]]
            
            severities_badges = []
            cve_ids = []
            for f in pkg_findings:
                sev_color = "red" if f.severity_level in ["CRITICAL", "HIGH"] else "yellow" if f.severity_level == "MEDIUM" else "blue"
                cvss_str = f" ({f.cvss_score})" if f.cvss_score else ""
                severities_badges.append(f"![{f.severity_level}](https://img.shields.io/badge/Severity-{f.severity_level}-{sev_color}){cvss_str}")
                cve_ids.append(f"[{f.vulnerability_id}]({f.references[0] if f.references else ''})")
            
            badg_str = " ".join(set(severities_badges))
            if not badg_str:
                badg_str = "Unknown"
            
            cve_str = "<br>".join(cve_ids) if cve_ids else "N/A"
            body.append(f"| `{change['package_name']}` | `{change['old_version']}` | `{change['new_version']}` | {badg_str} |")

        body.append("\n### 🚨 Advisory Details")
        
        for f in plan.report.findings:
            body.append(f"**{f.vulnerability_id}** (Package: `{f.package_name}`)")
            body.append(f"> {f.summary}")
            if f.references:
                body.append(f"> Reference: {f.references[0]}")
            body.append("")

        body.append("### 📝 Configuration Changes")
        body.append("```diff")
        body.append(plan.diff_text)
        body.append("```")
        body.append("\n### 🔐 Cryptographic Toolset Fingerprint Delta")
        body.append("*(Hashes currently computed by downstream verification)*")
        body.append("`old_hash` ➔ `new_hash`")

        body.append("\n---\n*Auto-generated by [MCP Vulnerability Bot](https://github.com/JMartynov/mcp-vulnerabilities)*")
        
        return "\n".join(body)

    def _get_existing_prs(self) -> list[dict]:
        """Fetch existing open PRs created by the bot."""
        if self.dry_run:
            return []
            
        try:
            res = self._run_cmd(["gh", "pr", "list", "--state", "open", "--json", "title,headRefName,url"], check=False)
            if res.returncode == 0:
                return json.loads(res.stdout.decode("utf-8"))
        except Exception as e:
            logger.warning(f"Failed to fetch PRs via gh cli: {e}")
        return []

    def create_or_update_pr(self, plan: RemediationPlan):
        """Creates a new branch and PR, or updates an existing PR for this vulnerability."""
        if not plan.changes:
            return

        # Use a combination of package names to name the branch
        pkgs = "_".join([c["package_name"].replace("@", "").replace("/", "_") for c in plan.changes])
        timestamp = datetime.now().strftime("%Y%m%d%H%M%S")
        branch_name = f"mcp-vuln/fix-{pkgs}-{timestamp}"
        
        existing_prs = self._get_existing_prs()
        for pr in existing_prs:
            if pr.get("headRefName", "").startswith(f"mcp-vuln/fix-{pkgs}"):
                logger.info(f"Open PR already exists for these packages: {pr['url']}")
                branch_name = pr['headRefName']
                # Continue and update the existing branch

        logger.info(f"Using branch {branch_name}")
        
        if not self.dry_run:
            # Checkout existing or create new
            res = self._run_cmd(["git", "checkout", branch_name], check=False)
            if res.returncode != 0:
                self._run_cmd(["git", "checkout", "-b", branch_name])
            
            # Write patched text to file
            plan.config_path.write_text(plan.patched_text, encoding="utf-8")
            
            # Commit changes
            self._run_cmd(["git", "add", str(plan.config_path)])
            commit_msg = f"Security: Update MCP servers to safe versions\n\nUpdates:\n" + \
                         "\n".join([f"- {c['package_name']}: {c['old_version']} -> {c['new_version']}" for c in plan.changes])
            self._run_cmd(["git", "commit", "-m", commit_msg])
            
            # Push branch
            self._run_cmd(["git", "push", "-u", "origin", branch_name])
            
        pr_title = f"Security: Update vulnerable MCP servers ({len(plan.changes)} packages)"
        pr_body = self.format_pr_body(plan)
        
        if self.dry_run:
            print(f"[DRY-RUN] Planned PR Title: {pr_title}")
            print(f"[DRY-RUN] Planned PR Body:\n{pr_body}")
            print(f"[DRY-RUN] Planned Branch: {branch_name}")
            print(f"[DRY-RUN] File to update: {plan.config_path}")
            return
            
        # Create PR if we didn't just update an existing one
        pr_exists = any(pr.get("headRefName") == branch_name for pr in existing_prs)
        
        if not pr_exists:
            gh_cmd = ["gh", "pr", "create", "--title", pr_title, "--body", pr_body, "--head", branch_name]
            if self.assignee:
                gh_cmd.extend(["--assignee", self.assignee])
                
            res = self._run_cmd(gh_cmd)
            if res.returncode == 0:
                pr_url = res.stdout.decode("utf-8").strip()
                logger.info(f"Successfully created PR: {pr_url}")
                
                if self.auto_merge:
                    self._run_cmd(["gh", "pr", "merge", pr_url, "--auto", "--squash"])
            else:
                logger.error(f"Failed to create PR: {res.stderr.decode('utf-8')}")

        # Checkout previous branch
        self._run_cmd(["git", "checkout", "-"])
